#!/bin/bash
# tako:run scripts/e2e/capture.sh
#
# 取り込み・永続化の隔離 E2E（受け入れ条件 3・4・5 とエッジケース）。
# 一般ペーストボードには触らない: 一意な名前の private ペーストボードを監視させ、そこへテストデータを書く。
#
#   MAKURIP_APP=path/to/Makurip.app scripts/e2e/capture.sh   # 入れた場所以外の .app で試す
#   KEEP_E2E=1 scripts/e2e/capture.sh                         # データフォルダを残す（調べる用）
set -euo pipefail
# shellcheck source=lib.sh
. "$(dirname "$0")/lib.sh"

build_devtool
new_run_dir capture
PB="com.takushio2525.makurip.e2e.$(uuidgen)"
trap 'finish_run; "$DEVTOOL" pb-release "$PB" > /dev/null 2>&1 || true' EXIT

write() {
    "$DEVTOOL" pb-write --pasteboard "$PB" --file-dir "$FILES" "$1" > /dev/null
    sleep "${2:-0.7}"
}

# 書いたら先頭がその種類になり、件数が 1 増える
expect_added() {
    local fixture="$1" kind="$2" before after
    before="$(item_count)"
    write "$fixture"
    after="$(item_count)"
    check "$fixture → 件数 +1" "$((before + 1))" "$after"
    check "$fixture → 種類" "$kind" "$(top_field kind)"
    echo "    $(top_summary)"
}

# 書いても件数が変わらない（保存しない）
expect_skipped() {
    local fixture="$1" before after
    before="$(item_count)"
    write "$fixture"
    after="$(item_count)"
    check "$fixture → 保存しない（件数そのまま）" "$before" "$after"
}

echo "== 起動（隔離: data=.e2e/$(basename "$RUN")/data, private ペーストボード）"
launch_instance --pasteboard-name "$PB"
TRUSTED="$(status_value '.accessibilityTrusted')"
echo "    accessibilityTrusted=$TRUSTED keyMonitorActive=$(status_value '.keyMonitorActive') hotKeys=$(status_value '.hotKeys|join(",")')"
check "起動直後は 0 件" "0" "$(item_count)"

echo "== 種類ごとの取り込み"
expect_added text text
expect_added rtf richText
expect_added image image
check "image → PNG と TIFF の両方を保存" "*public.png*public.tiff*" "$(dump | jq -r '[.items[0].pasteboardItems[][].type]|join(" ")')"
expect_added file file
check "file → ファイル URL を保存" "*public.file-url*" "$(dump | jq -r '[.items[0].pasteboardItems[][].type]|join(" ")')"
expect_added color color
expect_added code code
expect_added command command
expect_added url url
expect_added html richText

echo "== 保存しないもの（パスワード等の印・空の変化）"
expect_skipped concealed
expect_skipped transient
expect_skipped autogenerated
expect_skipped empty
check "ConcealedType 等の型を持つ項目がない" "0" \
    "$(dump | jq '[.items[].pasteboardItems[][].type | select(startswith("org.nspasteboard."))] | length')"

echo "== 型・項目の多いもの"
expect_added many-types text
check "many-types → 独自の型 40 個をすべて保存" "40" \
    "$(dump | jq '[.items[0].pasteboardItems[][].type | select(startswith("com.takushio2525.makurip.e2e.type-"))] | length')"
expect_added multi-item text
check "multi-item → 3 項目" "3" "$(dump | jq '.items[0].pasteboardItems|length')"

echo "== 大きいデータはディスクへ分けて置く・サイズ上限"
expect_added image-medium image
check "image-medium → 64 KB を超える型はファイルに置く" "file file" \
    "$(dump | jq -r '[.items[0].pasteboardItems[][].storage]|join(" ")')"
blob_files="$(find "$DATA/blobs" -type f -name '*.bin' | wc -l | tr -d ' ')"
check "image-medium → blobs/ にファイルが 2 つ" "2" "$blob_files"
expect_added image-large image
check "image-large → 上限超えの TIFF を落として PNG だけ" "public.png" "$(dump | jq -r '[.items[0].pasteboardItems[][].type]|join(" ")')"
check "image-large → truncated の印" "truncated" "$(top_field 'flags|join(",")')"
expect_skipped image-too-large

echo "== 重複（同じ内容は増やさず先頭へ）"
before="$(item_count)"
write fixed-text
write text
write fixed-text
check "fixed-text を 2 回 → 件数は +2（fixed-text 1 件 + text 1 件）" "$((before + 2))" "$(item_count)"
check "先頭は fixed-text で回数 2" "kind=text*copyCount=2" "$(top_summary)"

echo "== 記録の一時停止"
notify pause
sleep 0.3
before="$(item_count)"
write text
notify resume
sleep 1
check "一時停止中のコピーは再開後も保存しない" "$before" "$(item_count)"
expect_added text text

echo "== コピー方法"
notify simulateCopyShortcut
sleep 0.05
write command 1.2
KEY_METHOD="$(top_field copyMethod)"
write url 1.2
OTHER_METHOD="$(top_field copyMethod)"
if [ "$TRUSTED" = "true" ]; then
    check "⌘C の信号の直後に書いた → キー操作" "keyboard" "$KEY_METHOD"
    check "信号なしで書いた → それ以外" "other" "$OTHER_METHOD"
else
    echo "    （アクセシビリティ未許可なのでキー監視が効かない。どちらも unknown になるのが正しい）"
    check "未許可: ⌘C の信号があっても不明" "unknown" "$KEY_METHOD"
    check "未許可: 信号なしも不明" "unknown" "$OTHER_METHOD"
fi

echo "== 短い間隔で続けたコピー（0.05 秒おきに 10 回）"
before="$(item_count)"
for _ in $(seq 1 10); do
    "$DEVTOOL" pb-write --pasteboard "$PB" text > /dev/null
    sleep 0.05
done
sleep 1
captured=$(($(item_count) - before))
echo "    取り込めた数: $captured / 10（監視は 0.25 秒おき＋書き込みが落ち着くまで待つので、それより速く上書きされたコピーは最後の 1 回だけになる）"
in_range="$([ "$captured" -ge 1 ] && [ "$captured" -le 10 ] && echo ok || echo "$captured")"
check "短い間隔のコピーで 1 件以上・10 件以下を取り込む" "ok" "$in_range"

echo "== 再起動しても同じ（受け入れ条件 4）"
dump > "$RUN/dump-before.json"
quit_instance
check "終了した" "" "$(instance_pids)"
launch_instance --pasteboard-name "$PB"
dump > "$RUN/dump-after.json"
check "再起動の前後でメタデータが同じ" "same" "$(cmp -s "$RUN/dump-before.json" "$RUN/dump-after.json" && echo same || echo differ)"
echo "    件数: $(jq '.itemCount' "$RUN/dump-after.json")  種類の内訳: $(jq -r '[.items[].kind] | group_by(.) | map("\(.[0])=\(length)") | join(" ")' "$RUN/dump-after.json")"
echo "    コピー方法の内訳: $(jq -r '[.items[].copyMethod] | group_by(.) | map("\(.[0])=\(length)") | join(" ")' "$RUN/dump-after.json")"
echo "    ファイルに分けた型: $(jq '[.items[].pasteboardItems[][] | select(.storage == "file")] | length' "$RUN/dump-after.json") 個"

echo
echo "結果: OK=$PASS NG=$FAIL"
[ "$FAIL" -eq 0 ]
