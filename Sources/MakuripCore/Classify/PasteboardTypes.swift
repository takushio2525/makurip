/// nspasteboard.org の取り決め（と、それ以前から使われている同じ意味の型）。
/// これらの型が 1 つでも載っていたら、そのコピーは丸ごと保存しない。
public enum PasteboardMarkers {
    /// パスワード等。パスワード管理アプリが付ける
    public static let concealed = "org.nspasteboard.ConcealedType"
    /// 一時的な中身（すぐ消える前提でアプリが載せたもの）
    public static let transient = "org.nspasteboard.TransientType"
    /// ユーザーの操作でなくアプリが自動で載せたもの
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    public static let excluded: Set<String> = [
        concealed, transient, autoGenerated,
        // nspasteboard.org 以前からの同義の型（1Password・Butler・TypeIt4Me・KeeWeb 等）
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// AI の口（MCP・`--ai`）がクリップボードにも置いたときの印。保存はあちらで済んでいるので、監視は取り込まない（#6）
    public static let savedByMakuripAI = "com.takushio2525.makurip.saved-by-ai"

    /// 除外の型が含まれているか（型名だけを見る。データは読まない）
    public static func containsExcludedMarker(_ types: some Sequence<String>, extra: Set<String> = []) -> Bool {
        types.contains { excluded.contains($0) || extra.contains($0) }
    }

    /// 同じ内容かどうかの判定（ハッシュ）から外す型。コピーのたびに値が変わる付随情報
    public static let volatileTypePrefixes: [String] = [
        "org.nspasteboard.source",
        "org.chromium.internal.",
        "org.chromium.source-url",
        "com.apple.pasteboard.promised-",
    ]

    public static func isVolatile(_ type: String) -> Bool {
        volatileTypePrefixes.contains { type.hasPrefix($0) }
    }
}
