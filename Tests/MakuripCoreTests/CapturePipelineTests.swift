import Foundation
import Testing

@testable import MakuripCore

@Suite("取り込みの判定（除外・サイズ上限・ハッシュ）")
struct CapturePipelineTests {
    let context = CapturePipeline.Context(
        now: Date(timeIntervalSince1970: 100), frontmostApp: SourceApp(bundleID: "com.example.app", name: "Example"),
        copyMethod: .keyboard)

    @Test("ConcealedType・TransientType・AutoGeneratedType の付いた項目は保存しない")
    func excludedMarkers() {
        #expect(
            CapturePipeline.process(Fixtures.concealed, context: context, limits: .default) == .skip(.excludedMarker))
        for marker in [PasteboardMarkers.transient, PasteboardMarkers.autoGenerated, "com.agilebits.onepassword"] {
            let snapshot = Fixtures.text("generated", extra: [(marker, Data())])
            #expect(CapturePipeline.process(snapshot, context: context, limits: .default) == .skip(.excludedMarker))
        }
        // 2 つ目の項目にだけ印があっても丸ごと除外
        let mixed = Fixtures.items([
            [(PasteboardTypes.utf8PlainText, Data("a".utf8))],
            [(PasteboardTypes.utf8PlainText, Data("b".utf8)), (PasteboardMarkers.concealed, Data())],
        ])
        #expect(CapturePipeline.process(mixed, context: context, limits: .default) == .skip(.excludedMarker))
    }

    @Test("空の変化は保存しない")
    func empty() {
        #expect(
            CapturePipeline.process(PasteboardSnapshot(items: []), context: context, limits: .default) == .skip(.empty))
        let emptyItem = PasteboardSnapshot(items: [PasteboardItemSnapshot(representations: [])])
        #expect(CapturePipeline.process(emptyItem, context: context, limits: .default) == .skip(.empty))
    }

    @Test("取り込んだもののメタデータ")
    func metadata() throws {
        guard case .accept(let clip) = CapturePipeline.process(Fixtures.rtf, context: context, limits: .default) else {
            Issue.record("取り込まれなかった")
            return
        }
        #expect(clip.kind == .richText)
        #expect(clip.copyMethod == .keyboard)
        #expect(clip.source?.bundleID == "com.example.app")
        #expect(clip.capturedAt == Date(timeIntervalSince1970: 100))
        #expect(clip.previewText == "Makurip test")
        #expect(clip.flags.isEmpty)
        #expect(clip.snapshot == Fixtures.rtf)
    }

    @Test("型 1 つの上限を超えた型は落とし、残りは保存して truncated の印を付ける")
    func representationLimit() {
        var limits = Limits.default
        limits.maxRepresentationBytes = 10
        let snapshot = Fixtures.item([
            (PasteboardTypes.tiff, Data(count: 11)), (PasteboardTypes.png, Data(count: 10)),
        ])
        guard case .accept(let clip) = CapturePipeline.process(snapshot, context: context, limits: limits) else {
            Issue.record("取り込まれなかった")
            return
        }
        #expect(clip.snapshot.allTypes == [PasteboardTypes.png])
        #expect(clip.flags.contains(.truncated))
    }

    @Test("1 件の合計の上限を超えたら大きい型から落とす。何も残らなければ保存しない")
    func clipLimit() {
        var limits = Limits.default
        limits.maxClipBytes = 15
        let snapshot = Fixtures.item([
            (PasteboardTypes.utf8PlainText, Data(count: 5)), (PasteboardTypes.tiff, Data(count: 12)),
            (PasteboardTypes.png, Data(count: 8)),
        ])
        let (trimmed, dropped) = SizePolicy.trim(snapshot, limits: limits)
        #expect(trimmed.allTypes == [PasteboardTypes.utf8PlainText, PasteboardTypes.png])
        #expect(dropped == 1)

        limits.maxRepresentationBytes = 4
        #expect(CapturePipeline.process(snapshot, context: context, limits: limits) == .skip(.tooLarge))
    }

    @Test("読む段階で全部落ちた場合は tooLarge")
    func droppedWhileReading() {
        var droppedContext = context
        droppedContext.droppedWhileReading = 2
        #expect(
            CapturePipeline.process(PasteboardSnapshot(items: []), context: droppedContext, limits: .default)
                == .skip(.tooLarge))
    }

    @Test("同じ内容は同じハッシュ。コピーのたびに変わる付随情報の型は無視する")
    func hash() {
        let a = Fixtures.text("same", extra: [("org.chromium.internal.source-rfh-token", Data("token-1".utf8))])
        let b = Fixtures.text("same", extra: [("org.chromium.internal.source-rfh-token", Data("token-2".utf8))])
        #expect(ContentHasher.hash(a) == ContentHasher.hash(b))
        #expect(ContentHasher.hash(Fixtures.text("same")) != ContentHasher.hash(Fixtures.text("different")))
        // 型の組が違えば別物（同じ文字列でも RTF 付きは別の履歴）
        #expect(ContentHasher.hash(Fixtures.text("Makurip test")) != ContentHasher.hash(Fixtures.rtf))
        // 項目の区切りもハッシュに入る（"ab" 1 項目 と "a"+"b" 2 項目は別物）
        let split = Fixtures.items([
            [(PasteboardTypes.utf8PlainText, Data("a".utf8))], [(PasteboardTypes.utf8PlainText, Data("b".utf8))],
        ])
        #expect(ContentHasher.hash(split) != ContentHasher.hash(Fixtures.text("ab")))
    }

    @Test("一覧用の平文: ファイルは名前、画像はなし、長い文は切る")
    func preview() {
        #expect(PreviewText.make(for: Fixtures.finderFile, kind: .file, limit: 100) == "report.pdf")
        #expect(PreviewText.make(for: Fixtures.png, kind: .image, limit: 100) == nil)
        #expect(PreviewText.make(for: Fixtures.text("  abcdef  "), kind: .text, limit: 3) == "abc")
    }
}

@Suite("コピー元ページの URL")
struct SourceURLExtractorTests {
    @Test("Chromium の source-url")
    func chromium() {
        let snapshot = Fixtures.text(
            "copied", extra: [(PasteboardTypes.chromiumSourceURL, Data("https://example.com/page?a=1".utf8))])
        #expect(SourceURLExtractor.extract(from: snapshot) == "https://example.com/page?a=1")
    }

    @Test("WebKit の webarchive")
    func webArchive() throws {
        let plist: [String: Any] = ["WebMainResource": ["WebResourceURL": "https://www.apple.com/jp/"]]
        let data = try PropertyListSerialization.data(fromPropertyList: plist, format: .binary, options: 0)
        let snapshot = Fixtures.text("copied", extra: [(PasteboardTypes.webArchive, data)])
        #expect(SourceURLExtractor.extract(from: snapshot) == "https://www.apple.com/jp/")
    }

    @Test("ページ URL が載っていなければ nil（URL そのものをコピーした場合も）")
    func none() {
        #expect(SourceURLExtractor.extract(from: Fixtures.text("plain")) == nil)
        #expect(SourceURLExtractor.extract(from: Fixtures.text("https://example.com")) == nil)
        let local = Fixtures.text("x", extra: [(PasteboardTypes.chromiumSourceURL, Data("about:blank".utf8))])
        #expect(SourceURLExtractor.extract(from: local) == nil)
    }
}

@Suite("ショートカットの表記")
struct HotKeyTests {
    @Test("既定は ⌃⌘V")
    func defaultKey() {
        #expect(HotKey.defaultOpenHistory.displayString == "⌃⌘V")
        #expect(HotKey(keyCode: 8, modifiers: [.command, .shift, .option, .control]).displayString == "⌃⌥⇧⌘C")
    }

    @Test("設定に保存できる（Codable）")
    func codable() throws {
        let data = try JSONEncoder().encode(HotKey.defaultOpenHistory)
        #expect(try JSONDecoder().decode(HotKey.self, from: data) == HotKey.defaultOpenHistory)
    }
}
